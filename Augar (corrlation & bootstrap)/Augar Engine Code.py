def generate_cohort_user(user_id: int, n_days: int, pop_seed: int) -> tuple[pd.DataFrame, dict]:
    global GROUND_TRUTH # Reference the global GROUND_TRUTH

    # Each user gets a reproducible random stream based on a hash of their ID
    # and the population seed, so that changes to pop_seed affect everyone,
    # but individual users can be regenerated.
    rng = np.random.default_rng(abs(hash(f"{user_id}-{pop_seed}")) % (2**32 - 1))

    personal_ground_truth = []
    true_strengths = {}
    for inp, sym, sign, lag, pop_strength in GROUND_TRUTH:
        # lognormal-ish positive multiplier centered on 1.0, occasionally ~0
        mult = max(0.0, rng.normal(1.0, 0.45))
        if rng.random() < 0.15:
            mult *= rng.uniform(0.0, 0.2)  # non-responder for this pathway
        personal_ground_truth.append((inp, sym, sign, lag, pop_strength * mult))
        true_strengths[(inp, sym)] = sign * pop_strength * mult

    original_ground_truth = GROUND_TRUTH # Save the original global GROUND_TRUTH
    GROUND_TRUTH = personal_ground_truth # Temporarily set to personalized version
    try:
        df = generate_user(n_days=n_days, seed=int(rng.integers(1, 10**6))) # Use global generate_user
    finally:
        GROUND_TRUTH = original_ground_truth # Restore the original global GROUND_TRUTH
    return df, true_strengths

@dataclass
class PriorEstimate:
    key: tuple
    lag: int
    mu: float
    tau: float
    n_users: int
    prevalence: float

class PopulationPrior:
    def __init__(self):
      self.priors: dict[tuple, PriorEstimate] = {}

    def fit(self, per_user_estimates: dict[tuple, list[tuple]]):
        for key, rows in per_user_estimates.items():
            rs = np.array([r for r, _, _ in rows], dtype=float)
            ses = np.array([se for _, se, _ in rows], dtype=float)
            lags = [lag for _, _, lag in rows]
            if len(rs) < 3:
                continue  # too few users to call it a population effect
            mu = float(np.average(rs, weights=1.0 / np.maximum(ses**2, 1e-6)))
            # total variance of estimates = between-person (tau^2) + within (se^2)
            total_var = float(np.var(rs, ddof=1))
            mean_within = float(np.mean(ses**2))
            tau2 = max(0.0, total_var - mean_within)   # method-of-moments tau^2
            # prevalence: fraction whose own estimate is a non-trivial effect
            prevalence = float(np.mean(np.abs(rs) >= 0.15))
            lag_mode = max(set(lags), key=lags.count)

            self.priors[key] = PriorEstimate(
                key=key, lag=lag_mode, mu=mu, tau=math.sqrt(tau2),
                n_users=len(rs), prevalence=prevalence,
            )
    def predict(self, key, user_r=None, user_se=None):
        prior = self.priors.get(key)
        if prior is None:
            # nothing pooled for this pair; fall back to the user's own or zero
            return {"estimate": user_r if user_r is not None else 0.0,
                    "weight_personal": 1.0 if user_r is not None else 0.0,
                    "source": "personal_only", "lag": None}

        if user_r is None or user_se is None:
            return {"estimate": prior.mu, "weight_personal": 0.0,
                    "source": "population_prior", "lag": prior.lag,
                    "mu": prior.mu, "tau": prior.tau, "n_users": prior.n_users}

        tau2 = prior.tau**2
        w = tau2 / (tau2 + user_se**2 + 1e-9)        # reliability weight
        est = w * user_r + (1 - w) * prior.mu
        return {"estimate": float(est), "weight_personal": float(w),
                "source": "blended", "lag": prior.lag,
                "mu": prior.mu, "tau": prior.tau, "n_users": prior.n_users}

    def summary(self):
        return sorted(self.priors.values(), key=lambda p: -abs(p.mu))

    # ── persistence: this is the closest thing this model has to "weights" ────
    def save(self, path):
        """Save the fitted prior (the learned population parameters) to JSON."""
        payload = {
            "model": "PopulationPrior (empirical-Bayes shrinkage)",
            "n_relationships": len(self.priors),
            "priors": [
                {"input": p.key[0], "symptom": p.key[1], "lag": p.lag,
                 "mu": p.mu, "tau": p.tau, "n_users": p.n_users,
                 "prevalence": p.prevalence}
                for p in self.summary()
            ],
        }
        with open(path, "w") as f:
            json.dump(payload, f, indent=2)
        return path

    @classmethod
    def load(cls, path):
        """Reload a saved prior so a deployed app gives new users a head start."""
        with open(path) as f:
            payload = json.load(f)
        obj = cls()
        for r in payload["priors"]:
            key = (r["input"], r["symptom"])
            obj.priors[key] = PriorEstimate(
                key=key, lag=r["lag"], mu=r["mu"], tau=r["tau"],
                n_users=r["n_users"], prevalence=r["prevalence"],
            )
        return obj


CANDIDATE_PAIRS = [(i, s) for i, s, *_ in GROUND_TRUTH]


def estimate_pair(engine, df, inp, sym):
    """Raw (r, se, lag) for one (input, symptom) pair from one user's data."""
    frame = engine._prepare_frame(df)
    best = None
    for lag in range(engine.cfg.min_lag_days, engine.cfg.max_lag_days + 1):
        r, p, n = engine._partial_correlation(frame, inp, sym, lag)
        if np.isnan(r):
            continue
        if best is None or abs(r) > abs(best[0]):
            best = (r, lag, n)
    if best is None:
        return None
    r, lag, n = best
    if n < 5:
        return None
    se = math.sqrt(max(1e-6, (1 - r ** 2) / max(1, n - 2)))
    return (float(r), float(se), int(lag))


def fit_population(n_users=60, n_days=300, pop_seed=42):
    """Fit the population prior from many mature users' per-user estimates."""
    eng = PersonalCorrelationEngine(EngineConfig())
    per_pair = {pair: [] for pair in CANDIDATE_PAIRS}
    for u in range(n_users):
        df, _ = generate_cohort_user(u, n_days, pop_seed)
        for (inp, sym) in CANDIDATE_PAIRS:
            est = estimate_pair(eng, df, inp, sym)
            if est:
                per_pair[(inp, sym)].append(est)
    prior = PopulationPrior()
    prior.fit(per_pair)
    return prior


def _norm(signed_strength):
    """Squash a planted strength onto the correlation scale we compare on."""
    return float(np.tanh(signed_strength))


def evaluate_pooling(prior, days_grid, n_new_users=40, pop_seed=99):
    """New-user estimation error: engine-alone vs. pooled, vs. each user's truth."""
    eng = PersonalCorrelationEngine(EngineConfig())
    res = {"days": [], "engine_alone_mae": [], "pooled_mae": [], "engine_coverage": []}
    for days in days_grid:
        err_engine, err_pooled, covered = [], [], []
        for u in range(n_new_users):
            df, truth = generate_cohort_user(u, days, pop_seed)
            for pair in CANDIDATE_PAIRS:
                true_eff = _norm(truth[pair])
                est = estimate_pair(eng, df, pair[0], pair[1])
                if est:
                    r_i, se_i, _ = est
                    err_engine.append(abs(r_i - true_eff)); covered.append(1)
                    blend = prior.predict(pair, user_r=r_i, user_se=se_i)
                else:
                    err_engine.append(abs(0.0 - true_eff)); covered.append(0)
                    blend = prior.predict(pair, user_r=None, user_se=None)
                err_pooled.append(abs(blend["estimate"] - true_eff))
        res["days"].append(days)
        res["engine_alone_mae"].append(round(float(np.mean(err_engine)), 4))
        res["pooled_mae"].append(round(float(np.mean(err_pooled)), 4))
        res["engine_coverage"].append(round(float(np.mean(covered)), 3))
    return res


