@dataclass
class EngineConfig:
    min_lag_days: int = 0
    max_lag_days: int = 5

    min_paired_observations: int = 14

    min_effect_size: float = 0.20

    fdr_alpha: float = 0.10

    holdout_fraction: float = 0.30

    ridge_alpha: float = 1.0

    confounder_columns: tuple = ("stress_load", "sleep_debt", "dow_sin", "dow_cos")

    autoregressive_order: int = 2

@dataclass
class LaggedRelationship:
    input_name: str
    symptom_name: str
    best_lag_days: int
    effect_size: float          # partial correlation, signed
    direction: str              # "aggravates" | "relieves"
    p_value: float
    q_value: float              # FDR-adjusted
    n_observations: int
    distributed_lag_profile: dict = field(default_factory=dict)  # lag -> beta
    validated: Optional[bool] = None
    validation_detail: str = ""

    def human_summary(self) -> str:
        verb = "raises" if self.direction == "aggravates" else "lowers"
        lag = "same day" if self.best_lag_days == 0 else f"{self.best_lag_days}d later"
        conf = int((1 - self.q_value) * 100)
        return (f"{self.input_name} {verb} {self.symptom_name} ({lag}, "
                f"r={self.effect_size:+.2f}, ~{conf}% conf, n={self.n_observations})")


@dataclass
class Hypothesis:
    statement: str
    input_name: str
    symptom_name: str
    lag_days: int
    predicted_direction: str
    predicted_effect: float
    confidence: float
    based_on_relationship: LaggedRelationship


@dataclass
class HypothesisResult:
    hypothesis: Hypothesis
    confirmed: bool
    observed_effect: float
    observed_p: float
    verdict: str

class PersonalCorrelationEngine:

    def __init__(self, config: EngineConfig | None = None):
        self.cfg = config or EngineConfig()
        self.audit_trail: list[LaggedRelationship] = []

    def discover(
        self,
        df: pd.DataFrame,
        input_columns: list[str],
        symptom_columns: list[str],
    ) -> list[LaggedRelationship]:

        df = self._prepare_frame(df)

        # 1. Estimate every (input, symptom) distributed-lag relationship on the
        #    TRAIN portion only.
        split = int(len(df) * (1 - self.cfg.holdout_fraction))
        train, test = df.iloc[:split], df.iloc[split:]

        candidates: list[LaggedRelationship] = []
        for sym in symptom_columns:
            for inp in input_columns:
                rel = self._estimate_relationship(train, inp, sym)
                if rel is not None:
                    candidates.append(rel)

        self.audit_trail = candidates  # full record, including everything rejected
        if not candidates:
            return []

        candidates = self._apply_fdr(candidates)

        survivors = [
            c for c in candidates
            if c.q_value <= self.cfg.fdr_alpha
            and abs(c.effect_size) >= self.cfg.min_effect_size
        ]

        signals = []
        for rel in survivors:
            self._validate_out_of_sample(test, rel)
            if rel.validated:
                signals.append(rel)

        return sorted(signals, key=lambda r: r.q_value)

    def generate_hypothesis(
        self, relationships: list[LaggedRelationship]
    ) -> Optional[Hypothesis]:

        validated = [r for r in relationships if r.validated]
        if not validated:
            return None
        r = max(validated, key=lambda x: abs(x.effect_size))

        if r.direction == "aggravates":
            stmt = (f"Reducing {r.input_name} this week should LOWER your "
                    f"{r.symptom_name} at a ~{r.best_lag_days}-day lag.")
        else:
            stmt = (f"Increasing {r.input_name} this week should LOWER your "
                    f"{r.symptom_name} at a ~{r.best_lag_days}-day lag.")

        return Hypothesis(
            statement=stmt,
            input_name=r.input_name,
            symptom_name=r.symptom_name,
            lag_days=r.best_lag_days,
            predicted_direction=r.direction,
            predicted_effect=r.effect_size,
            confidence=1 - r.q_value,
            based_on_relationship=r,
        )

    def evaluate_hypothesis(
        self, hypothesis: Hypothesis, week_df: pd.DataFrame
    ) -> HypothesisResult:
        week_df = self._prepare_frame(week_df)
        x, y = self._lagged_pairs(
            week_df, hypothesis.input_name, hypothesis.symptom_name,
            hypothesis.lag_days,
        )
        if len(x) < 4:
            return HypothesisResult(
                hypothesis, confirmed=False, observed_effect=np.nan,
                observed_p=np.nan,
                verdict="Inconclusive — not enough data logged this week.",
            )
        r, p = stats.spearmanr(x, y)
        same_sign = (r > 0) == (hypothesis.predicted_direction == "aggravates")
        confirmed = bool(same_sign and p < 0.10)
        verdict = (
            f"Confirmed. {hypothesis.symptom_name} moved as predicted "
            f"(r={r:+.2f}, p={p:.2f})."
            if confirmed else
            f"Not confirmed this week (r={r:+.2f}, p={p:.2f}). The model will "
            f"down-weight this relationship."
        )
        return HypothesisResult(hypothesis, confirmed, float(r), float(p), verdict)


    def _prepare_frame(self, df: pd.DataFrame) -> pd.DataFrame:
        df = df.copy()
        if not isinstance(df.index, pd.DatetimeIndex):
            if "date" in df.columns:
                df = df.set_index(pd.to_datetime(df["date"])).drop(columns=["date"])
            else:
                df.index = pd.to_datetime(df.index)
        df = df.sort_index()
        # Engineer cyclical day-of-week confounders (handles the "Tuesday" problem).
        dow = df.index.dayofweek
        df["dow_sin"] = np.sin(2 * np.pi * dow / 7)
        df["dow_cos"] = np.cos(2 * np.pi * dow / 7)
        return df

    def _build_confounders(self, frame: pd.DataFrame, symptom: str) -> pd.DataFrame:
        cols = {}
        for c in self.cfg.confounder_columns:
            if c in frame.columns:
                cols[c] = frame[c]
        # Autoregressive lags of the symptom itself.
        for k in range(1, self.cfg.autoregressive_order + 1):
            cols[f"{symptom}_ar{k}"] = frame[symptom].shift(k)
        return pd.DataFrame(cols, index=frame.index)

    def _estimate_relationship(
        self, frame: pd.DataFrame, inp: str, sym: str
    ) -> Optional[LaggedRelationship]:
        lags = list(range(self.cfg.min_lag_days, self.cfg.max_lag_days + 1))

        per_lag = []
        for L in lags:
            r, p, n = self._partial_correlation(frame, inp, sym, L)
            if not np.isnan(r):
                per_lag.append((L, r, p, n))
        if not per_lag:
            return None

        # Strongest lag by |partial r|.
        best_lag, best_r, best_p, n = max(per_lag, key=lambda t: abs(t[1]))

        # Within-pair correction for the lag search. Adjacent lags of a bursty
        # food are correlated, so the effective number of independent tests is
        # less than len(lags); estimate it and apply a Sidak adjustment on the
        # effective number of independent lags. The pair-level p that results
        # is the correct unit for the across-pair FDR step that follows.

        # Returns None if there isn't enough overlapping data.

        m_eff = self._effective_tests(frame, inp, lags)
        pair_p = 1.0 - (1.0 - best_p) ** m_eff
        pair_p = float(min(pair_p, 1.0))

        # Descriptive distributed-lag profile (signed partial r at each lag).
        lag_profile = {int(L): float(r) for L, r, _, _ in per_lag}

        return LaggedRelationship(
            input_name=inp,
            symptom_name=sym,
            best_lag_days=int(best_lag),
            effect_size=float(best_r),
            direction="aggravates" if best_r > 0 else "relieves",
            p_value=pair_p,
            q_value=1.0,  # filled in by FDR step
            n_observations=int(n),
            distributed_lag_profile=lag_profile,
        )

    def _effective_tests(self, frame: pd.DataFrame, inp: str, lags: list[int]) -> float:
        cols = {f"{inp}_lag{L}": frame[inp].shift(L) for L in lags}
        M = pd.DataFrame(cols).dropna()
        m = len(lags)
        if len(M) < m + 2:
            return float(m)
        try:
            corr = np.corrcoef(M.values, rowvar=False)
            eig = np.linalg.eigvalsh(corr)
            eig = np.clip(eig, 0, None)
            var_eig = np.var(eig, ddof=1)
            m_eff = 1 + (m - 1) * (1 - var_eig / m)
            return float(np.clip(m_eff, 1.0, m))
        except Exception:
            return float(m)

    @staticmethod
    def _rss(design: np.ndarray, y: np.ndarray) -> float:
        beta, *_ = np.linalg.lstsq(design, y, rcond=None)
        resid = y - design @ beta
        return float(resid @ resid)

    def _partial_correlation(self, frame, inp, sym, lag):
        C = self._build_confounders(frame, sym)
        x = frame[inp].shift(lag)
        y = frame[sym]
        data = pd.concat([x.rename("x"), y.rename("y"), C], axis=1).dropna()
        n = len(data)
        if n < self.cfg.min_paired_observations:
            return np.nan, np.nan, n

        ctrl = data.drop(columns=["x", "y"]).values
        if ctrl.shape[1] == 0:
            r, p = stats.pearsonr(data["x"], data["y"])
            return r, p, n

        # Residualize x and y against controls, then correlate residuals.
        ctrl_design = np.column_stack([np.ones(n), ctrl])
        bx, *_ = np.linalg.lstsq(ctrl_design, data["x"].values, rcond=None)
        by, *_ = np.linalg.lstsq(ctrl_design, data["y"].values, rcond=None)
        rx = data["x"].values - ctrl_design @ bx
        ry = data["y"].values - ctrl_design @ by
        if np.std(rx) < 1e-9 or np.std(ry) < 1e-9:
            return np.nan, np.nan, n
        r, p = stats.pearsonr(rx, ry)
        # Adjust p for the dof spent on controls.
        return r, p, n

    def _apply_fdr(self, candidates: list[LaggedRelationship]):
        pvals = np.array([c.p_value for c in candidates])
        order = np.argsort(pvals)
        m = len(pvals)
        q = np.empty(m)
        prev = 1.0
        # Step-up from largest p to smallest.
        for rank in range(m - 1, -1, -1):
            idx = order[rank]
            val = pvals[idx] * m / (rank + 1)
            prev = min(prev, val)
            q[idx] = min(prev, 1.0)
        for c, qv in zip(candidates, q):
            c.q_value = float(qv)
        return candidates

    def _lagged_pairs(self, frame, inp, sym, lag):
        x = frame[inp].shift(lag)
        y = frame[sym]
        d = pd.concat([x.rename("x"), y.rename("y")], axis=1).dropna()
        return d["x"].values, d["y"].values

    def _validate_out_of_sample(self, test_df, rel: LaggedRelationship):
        x, y = self._lagged_pairs(test_df, rel.input_name, rel.symptom_name,
                                  rel.best_lag_days)
        if len(x) < 6:
            rel.validated = None
            rel.validation_detail = "Insufficient holdout data to validate."
            return
        with warnings.catch_warnings():
            warnings.simplefilter("ignore")
            r, p = stats.spearmanr(x, y)
        # The direction for 'aggravates' means a positive correlation.
        # So r > 0 should correspond to 'aggravates'.
        same_sign = (r > 0) == (rel.direction == "aggravates")
        rel.validated = bool(same_sign and p < 0.20)
        rel.validation_detail = (
            f"Holdout: r={r:+.2f}, p={p:.2f}, n={len(x)} "
            f"({'reproduced' if rel.validated else 'did not reproduce'})."
        )

