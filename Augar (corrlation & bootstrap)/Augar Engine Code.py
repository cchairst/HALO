GROUND_TRUTH = [
    # (input, symptom, sign, lag_days, strength)   sign: +1 aggravates, -1 relieves
    ("seed_oil", "joint_pain", +1, 2, 0.9),
    ("omega3",   "mood",       -1, 2, 0.8),   # mood scored so higher = worse here
    ("sugar",    "fatigue",    +1, 0, 1.2),
    ("turmeric", "joint_pain", -1, 4, 0.6),
]

DECOY_INPUTS = ["coffee", "pasta", "cheese", "banana", "salad", "soda", "bread", "eggs"]
SYMPTOMS = ["joint_pain", "mood", "fatigue", "cognitive_clarity", "sleep_quality"]

def generate_user(
    n_days: int = 120,
    missingness: float = 0.12,
    noise: float = 1.0,
    seed: int = 7,
    ) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    dates = pd.date_range("2025-01-01", periods=n_days, freq="D")

    inputs = {}
    real_inputs = [g[0] for g in GROUND_TRUTH]
    for name in real_inputs + DECOY_INPUTS:
        # Bursty intake: people eat foods in runs, not i.i.d.
        base = rng.random(n_days)
        smoothed = pd.Series(base).rolling(3, min_periods=1).mean().values
        inputs[name] = (smoothed * rng.uniform(0.8, 1.4)).round(2)
    X = pd.DataFrame(inputs, index=dates)

    stress = pd.Series(rng.normal(0, 1, n_days), index=dates) \
        .rolling(4, min_periods=1).mean()
    sleep_debt = pd.Series(rng.normal(0, 1, n_days), index=dates) \
        .rolling(3, min_periods=1).mean()

    symptoms = {}
    for s in SYMPTOMS:
        series = np.zeros(n_days)
        prev = rng.normal(5, 1.0)
        for t in range(n_days):
            # sticky autoregression — yesterday predicts today (moderate)
            val = 0.45 * prev + 0.55 * 5.0
            # confounders nudge several symptoms (a real, modest confound)
            val += 0.5 * stress.iloc[t]
            if s in ("fatigue", "cognitive_clarity", "sleep_quality"):
                val += 0.4 * sleep_debt.iloc[t]
            val += rng.normal(0, 0.9 * noise)
            series[t] = val
            prev = val
        symptoms[s] = series

    for inp, sym, sign, lag, strength in GROUND_TRUTH:
        x = X[inp].values
        for t in range(n_days):
            src = t - lag
            if src >= 0:
                symptoms[sym][t] += sign * 3.3 * strength * (x[src] - x.mean())

    Y = pd.DataFrame(symptoms, index=dates)
    # clip to a 0-10 clinical scale and round (mirrors a 0-10 symptom slider)
    Y = Y.apply(lambda c: np.clip(c, 0, 10)).round(0)

    df = pd.concat([X, Y, stress.rename("stress_load"),
                    sleep_debt.rename("sleep_debt")], axis=1)

    mask = rng.random((n_days, len(SYMPTOMS))) < missingness
    for j, s in enumerate(SYMPTOMS):
        df.loc[mask[:, j], s] = np.nan

    df.index.name = "date"
    return df

def input_columns():
    return [g[0] for g in GROUND_TRUTH] + DECOY_INPUTS


